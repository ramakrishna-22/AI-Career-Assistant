package com.careerassistant;

import com.careerassistant.dto.ResumeAnalysisResponse;
import com.careerassistant.dto.ResumeResponse;
import com.careerassistant.entity.Resume;
import com.careerassistant.entity.User;
import com.careerassistant.exception.InvalidFileException;
import com.careerassistant.exception.ResourceNotFoundException;
import com.careerassistant.repository.ResumeRepository;
import com.careerassistant.repository.UserRepository;
import com.careerassistant.service.ResumeAnalysisService;
import com.careerassistant.service.ResumeService;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.core.io.Resource;
import org.springframework.mock.web.MockMultipartFile;
import org.springframework.transaction.annotation.Transactional;

import java.io.File;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.List;

import static org.junit.jupiter.api.Assertions.*;

@SpringBootTest
@Transactional
public class ResumeIntegrationTest {

    @Autowired
    private ResumeService resumeService;

    @Autowired
    private ResumeAnalysisService resumeAnalysisService;

    @Autowired
    private UserRepository userRepository;

    @Autowired
    private ResumeRepository resumeRepository;

    private User testUser;
    private User otherUser;
    private byte[] validPdfBytes;

    @BeforeEach
    public void setUp() throws Exception {
        // Create test user 1
        if (!userRepository.existsByEmail("testuser@example.com")) {
            User u = new User();
            u.setName("Test User");
            u.setEmail("testuser@example.com");
            u.setPassword("Password123");
            testUser = userRepository.save(u);
        } else {
            testUser = userRepository.findByEmail("testuser@example.com").get();
        }

        // Create test user 2 (unauthorized comparison)
        if (!userRepository.existsByEmail("otheruser@example.com")) {
            User u2 = new User();
            u2.setName("Other User");
            u2.setEmail("otheruser@example.com");
            u2.setPassword("Password123");
            otherUser = userRepository.save(u2);
        } else {
            otherUser = userRepository.findByEmail("otheruser@example.com").get();
        }

        // Read the sample PDF generated by CreateTestPdfTest
        Path samplePdfPath = Paths.get("E:/AI-Career-Assistant/sample/real_sample_resume.pdf");
        assertTrue(Files.exists(samplePdfPath), "Sample PDF must exist at E:/AI-Career-Assistant/sample/real_sample_resume.pdf");
        validPdfBytes = Files.readAllBytes(samplePdfPath);
    }

    @Test
    public void testCompleteResumeLifecycleAndValidations() throws Exception {
        // 1. Valid PDF upload -> success
        MockMultipartFile pdfMultipart = new MockMultipartFile(
                "file",
                "real_sample_resume.pdf",
                "application/pdf",
                validPdfBytes
        );

        ResumeResponse uploadResponse = resumeService.uploadResume(pdfMultipart, testUser.getId());
        assertNotNull(uploadResponse);
        assertNotNull(uploadResponse.getId());
        assertEquals("real_sample_resume.pdf", uploadResponse.getFileName());

        // 2. PDF stored on disk -> success
        Resume resumeEntity = resumeRepository.findById(uploadResponse.getId()).orElseThrow();
        File storedFile = new File(resumeEntity.getFilePath());
        assertTrue(storedFile.exists(), "Stored file must exist on disk");
        assertTrue(storedFile.length() > 0, "Stored file size must be > 0 bytes");

        // 3. Database metadata saved -> success
        assertEquals(testUser.getId(), resumeEntity.getUser().getId());
        assertEquals("application/pdf", resumeEntity.getFileType());
        assertEquals(validPdfBytes.length, resumeEntity.getFileSize());

        // 4. Get user resumes -> success
        List<ResumeResponse> userResumes = resumeService.getUserResumes(testUser.getId());
        assertFalse(userResumes.isEmpty());
        assertTrue(userResumes.stream().anyMatch(r -> r.getId().equals(uploadResponse.getId())));

        // 5. Analyze valid resume -> success
        ResumeAnalysisResponse analysis = resumeAnalysisService.analyzeResume(uploadResponse.getId(), testUser.getId());
        assertNotNull(analysis);
        assertTrue(analysis.getWordCount() > 0);
        assertTrue(analysis.getCharacterCount() > 0);
        assertTrue(analysis.isEmailDetected(), "Email ram@example.com should be detected");
        assertTrue(analysis.isPhoneDetected(), "Phone number should be detected");
        assertTrue(analysis.getSkills().contains("Java"), "Skills should contain Java");
        assertTrue(analysis.getSkills().contains("Spring Boot"), "Skills should contain Spring Boot");
        assertTrue(analysis.getDetectedSections().contains("Education"), "Sections should contain Education");
        assertTrue(analysis.getDetectedSections().contains("Projects"), "Sections should contain Projects");
        assertTrue(analysis.getBasicScore() > 0, "Score should be calculated");

        // 6. Download resume -> success
        Resource resource = resumeService.loadResumeAsResource(uploadResponse.getId(), testUser.getId());
        assertNotNull(resource);
        assertTrue(resource.exists());

        // 7. Unauthorized analysis -> rejected
        assertThrows(ResourceNotFoundException.class, () -> {
            resumeAnalysisService.analyzeResume(uploadResponse.getId(), otherUser.getId());
        }, "Analyzing another user's resume should be rejected");

        // 8. Unauthorized download -> rejected
        assertThrows(ResourceNotFoundException.class, () -> {
            resumeService.loadResumeAsResource(uploadResponse.getId(), otherUser.getId());
        }, "Downloading another user's resume should be rejected");

        // 9. Missing file -> rejected
        MockMultipartFile emptyFile = new MockMultipartFile("file", "", "application/pdf", new byte[0]);
        assertThrows(InvalidFileException.class, () -> {
            resumeService.uploadResume(emptyFile, testUser.getId());
        }, "Empty file upload should be rejected");

        // 10. Invalid file type -> rejected
        MockMultipartFile exeFile = new MockMultipartFile("file", "malicious.exe", "application/x-msdownload", "fake content".getBytes());
        assertThrows(InvalidFileException.class, () -> {
            resumeService.uploadResume(exeFile, testUser.getId());
        }, "Invalid extension upload should be rejected");

        System.out.println("=== ALL 10 WEEK 2 TEST CASES PASSED SUCCESSFULLY ===");
    }
}
